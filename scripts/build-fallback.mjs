#!/usr/bin/env node
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { stripTypeScriptTypes } from 'node:module'

const ID = '@cbh0920/dsh-client-ui-skin-arknights-amiya'
const STYLE_ID = `${ID}/arknights-amiya.module.css`

function rootPath(value) {
  if (value instanceof URL) return fileURLToPath(value)
  return resolve(String(value))
}

function stripExports(source) {
  let js = stripTypeScriptTypes(source, { mode: 'transform', sourceMap: false })
  js = js.replace(/\bexport\s+(?=(?:const|let|var|function|class)\b)/g, '')
  js = js.replace(/^\s*export\s+\{[^}]+\}\s+from\s+[^\n]+$/gm, '')
  return js
}

async function selectedArtSource(repoRoot) {
  return { path: resolve(repoRoot, 'src/client/amiya-art.ts'), symbol: 'AMIYA_ART' }
}

export async function buildFallbackBundle(repoRootInput) {
  const repoRoot = rootPath(repoRootInput)
  const outDir = resolve(repoRoot, 'lib')
  await mkdir(outDir, { recursive: true })

  const lifecycleTs = await readFile(resolve(repoRoot, 'src/client/lifecycle.ts'), 'utf8')
  const cssText = await readFile(resolve(repoRoot, 'src/client/arknights-amiya.module.css'), 'utf8')
  const artInfo = await selectedArtSource(repoRoot)
  const artTs = await readFile(artInfo.path, 'utf8')

  const lifecycleJs = stripExports(lifecycleTs)
  let artJs = stripExports(artTs)
  artJs = artJs.replaceAll(artInfo.symbol, 'AMIYA_ART')

  const client = [
    `window.__ModuleLoader__.load({ id: ${JSON.stringify(ID)}, factory: (require) => {`,
    'var module = { exports: {} }; var exports = module.exports;',
    `const __cssText = ${JSON.stringify(cssText)};`,
    `const __styleId = ${JSON.stringify(STYLE_ID)};`,
    "if (typeof document !== 'undefined' && document.querySelector('style[data-plugin-css=' + JSON.stringify(__styleId) + ']') === null) {",
    "  const __style = document.createElement('style');",
    `  __style.dataset.plugin = ${JSON.stringify(ID)};`,
    '  __style.dataset.pluginCss = __styleId;',
    '  __style.textContent = __cssText;',
    '  document.head.appendChild(__style);',
    '}',
    artJs,
    lifecycleJs,
    "const css = new Proxy(Object.create(null), { get: (_target, key) => typeof key === 'string' ? key : '' });",
    'exports.apply = (ctx) => applyAmiyaSkin(ctx, css, AMIYA_ART);',
    'exports.SKIN_TITLE = SKIN_TITLE;',
    'return module.exports; } });',
    '',
  ].join('\n')

  const host = [
    '/** Prebuilt host entry generated by scripts/build-fallback.mjs. */',
    'export function apply() {}',
    '',
  ].join('\n')

  const clientPath = resolve(outDir, 'client.js')
  const hostPath = resolve(outDir, 'index.js')
  await writeFile(clientPath, client, 'utf8')
  await writeFile(hostPath, host, 'utf8')
  return { client: clientPath, host: hostPath }
}

async function main() {
  const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
  const result = await buildFallbackBundle(repoRoot)
  console.log(`Fallback bundle written:\n- ${result.host}\n- ${result.client}`)
}

const cliPath = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : ''
if (cliPath === import.meta.url) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.stack : String(error))
    process.exitCode = 1
  })
}
